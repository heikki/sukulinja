function layersFor(sex: string | null) {
  if (sex === 'F') return FEMALE;
  if (sex === 'M') return MALE;
  return UNKNOWN;
}

export function silhouette(
  sex: string | null,
  cx: number,
  cy: number,
  r: number
) {
  return svg`
    <g class="silhouette" transform="translate(${cx} ${cy}) scale(${r})">
      <circle class="silhouette-bg" r="1" />
      ${layersFor(sex).map(([tone, d]) => svg`<path class=${tone} d=${d} />`)}
    </g>
  `;
}

